# Export the "NestCoop Avatar" collection of art/avatar-head.blend to NestCoop/Assets/avatar-head.mesh.txt,
# which is embedded in NestCoop.dll and turned into Unity meshes by NestCoop/AvatarModel.cs.
#
# Run in Blender (Scripting tab, or via the Blender MCP):  exec(open(bpy.path.abspath("//export_avatar.py")).read())
#
# Format (text, one record per line):
#   # comment
#   g <material> <r> <g> <b> <metallic> <smoothness>   start a group (colour in sRGB 0..1)
#   t x y z x y z x y z                                 one triangle, Unity coordinates, Unity winding
# Coordinates: Blender is right-handed Z-up with the face looking -Y; Unity is left-handed Y-up looking +Z.
# Character right (Blender -X) -> Unity +X, up (Blender +Z) -> Unity +Y, forward (Blender -Y) -> Unity +Z:
#   unity = (-x, z, -y)   (a mirror, so the triangle winding is reversed too)
# The origin is eye level, which the mod puts at the player's view point.
import bpy, os

COLLECTION = "NestCoop Avatar"
if not bpy.data.filepath:
    raise RuntimeError("Open art/avatar-head.blend from the repo first (the output path is found from it)")
repo = os.path.dirname(os.path.dirname(bpy.data.filepath))
out = os.path.join(repo, "NestCoop", "Assets", "avatar-head.mesh.txt")

def to_srgb(c):
    return c * 12.92 if c <= 0.0031308 else 1.055 * (c ** (1 / 2.4)) - 0.055

def u(v):
    return (-v.x, v.z, -v.y)

groups = {}   # material name -> (colour, metallic, smoothness, [triangles])
deps = bpy.context.evaluated_depsgraph_get()
for obj in bpy.data.collections[COLLECTION].all_objects:
    if obj.type != 'MESH' or obj.hide_get():
        continue
    ev = obj.evaluated_get(deps)
    mesh = ev.to_mesh()
    mesh.calc_loop_triangles()
    mw = obj.matrix_world
    for tri in mesh.loop_triangles:
        mat = obj.material_slots[tri.material_index].material if obj.material_slots else None
        name = mat.name if mat else "Default"
        if name not in groups:
            rgb, metal, smooth = (0.8, 0.8, 0.8), 0.0, 0.3
            if mat and mat.use_nodes and mat.node_tree.nodes.get("Principled BSDF"):
                b = mat.node_tree.nodes["Principled BSDF"]
                rgb = tuple(to_srgb(c) for c in b.inputs["Base Color"].default_value[:3])
                metal = b.inputs["Metallic"].default_value
                smooth = 1.0 - b.inputs["Roughness"].default_value
            groups[name] = (rgb, metal, smooth, [])
        a, b2, c = (mw @ mesh.vertices[i].co for i in tri.vertices)
        groups[name][3].append((a.copy(), c.copy(), b2.copy()))   # reversed winding
    ev.to_mesh_clear()

# Normalise, so the model can be edited at any scale: HEIGHT metres tall, origin at eye level = centre of the
# "Lens" triangles (the goggles), else the centre of the bounding box.
HEIGHT = 0.23
from mathutils import Vector
allp = [p for g in groups.values() for t in g[3] for p in t]
zmin, zmax = min(p.z for p in allp), max(p.z for p in allp)
k = HEIGHT / (zmax - zmin)
lens = [p for t in groups.get("Lens", (0, 0, 0, []))[3] for p in t]
pts = lens or allp
eye = Vector((0, sum(p.y for p in pts) / len(pts), sum(p.z for p in pts) / len(pts))) if lens else \
      Vector((0, (min(p.y for p in allp) + max(p.y for p in allp)) / 2, (zmin + zmax) / 2))
eye.y = 0  # keep the head centred front-to-back on the pivot; only drop the origin to eye height
for g in groups.values():
    g[3][:] = [tuple(u((p - eye) * k) for p in t) for t in g[3]]

os.makedirs(os.path.dirname(out), exist_ok=True)
total = 0
with open(out, "w", encoding="ascii", newline="\n") as f:
    f.write("# NestCoop avatar head v1 - generated by art/export_avatar.py from art/avatar-head.blend; do not edit\n")
    for name, (rgb, metal, smooth, tris) in groups.items():
        f.write(f"g {name} {rgb[0]:.4f} {rgb[1]:.4f} {rgb[2]:.4f} {metal:.3f} {smooth:.3f}\n")
        for t in tris:
            f.write("t " + " ".join(f"{c:.5f}" for p in t for c in p) + "\n")
        total += len(tris)
result = {"file": out, "groups": {k: len(v[3]) for k, v in groups.items()}, "triangles": total}
